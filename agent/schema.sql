CREATE TABLE IF NOT EXISTS agent_products (
 id VARCHAR(100) PRIMARY KEY,
 document JSON NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS agent_departures (
 product_id VARCHAR(100) NOT NULL,
 tour_date DATE NOT NULL,
 capacity INT UNSIGNED NOT NULL,
 reserved INT UNSIGNED NOT NULL DEFAULT 0,
 open BOOLEAN NOT NULL DEFAULT FALSE,
 cutoff DATETIME NOT NULL,
 PRIMARY KEY(product_id,tour_date),
 FOREIGN KEY(product_id) REFERENCES agent_products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS agent_quotes (
 id CHAR(36) PRIMARY KEY,
 session_id CHAR(64) NOT NULL,
 product_id VARCHAR(100) NOT NULL,
 document JSON NOT NULL,
 expires_at DATETIME NOT NULL,
 INDEX(session_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS agent_bookings (
 reference VARCHAR(40) PRIMARY KEY,
 quote_id CHAR(36) NOT NULL UNIQUE,
 session_id CHAR(64) NOT NULL,
 document JSON NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(session_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS agent_enquiries (
 id CHAR(36) PRIMARY KEY,
 dedupe CHAR(64) NOT NULL UNIQUE,
 kind VARCHAR(16) NOT NULL,
 document JSON NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
